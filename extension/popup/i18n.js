  function create(dependencies) {
    const options = dependencies || {};
    const documentApi = options.document || globalScope.document;
    if (!documentApi || typeof documentApi.querySelectorAll !== "function") {
      throw new Error("Popup I18n requires document.querySelectorAll.");
    }

    let currentLang = ["zh", "en"].includes(options.defaultLanguage)
      ? options.defaultLanguage
      : "zh";

    function t(key) {
      return (STRINGS[currentLang] && STRINGS[currentLang][key]) || STRINGS.en[key] || key;
    }

    function applyLanguage(lang) {
      currentLang = ["zh", "en"].includes(lang) ? lang : "zh";
      documentApi.querySelectorAll("[data-i18n]").forEach(function(el) {
        var key = el.getAttribute("data-i18n");
        if (key) el.textContent = t(key);
      });
      documentApi.querySelectorAll("[data-i18n-placeholder]").forEach(function(el) {
        var key = el.getAttribute("data-i18n-placeholder");
        if (key) el.placeholder = t(key);
      });
    }

    function getLanguage() {
      return currentLang;
    }

    return Object.freeze({
      applyLanguage,
      getLanguage,
      strings: STRINGS,
      t,
    });
  }

  popup.I18n = Object.freeze({ create });
